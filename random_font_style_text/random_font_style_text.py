def convert_to_style(text, style_map):
    """Convert text using the given style mapping."""
    return ''.join(style_map.get(char, char) for char in text)

def get_random_styles(text, num_styles=3):
    """Generate multiple random styled versions of the text."""
    styles = list(STYLE_MAPS.keys())
    selected_styles = random.sample(styles, min(num_styles, len(styles)))
    return {style: convert_to_style(text, STYLE_MAPS[style]) for style in selected_styles}

def display_styled_text(styled_texts):
    """Display styled text outputs."""
    print("\n" + "="*50)
    print("Random Font Style Text Output")
    print("="*50)
    for style_name, styled_text in styled_texts.items():
        print(f"\n{style_name.upper()} Style:")
        print(styled_text)
    print("\n" + "="*50)

